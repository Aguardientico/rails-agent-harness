# frozen_string_literal: true

require "rails_agent_harness/guards/migration_guard"

RSpec.describe RailsAgentHarness::Guards::MigrationGuard do
  around do |example|
    Dir.mktmpdir("agent_harness_guard") do |dir|
      @root = dir
      example.run
    end
  end

  attr_reader :root

  def guard(yaml = nil)
    described_class.new(root: root, config: load_config(root, yaml))
  end

  def call(tool_name, file_path, guard: self.guard)
    guard.pre_tool_use("tool_name" => tool_name, "tool_input" => {"file_path" => file_path})
  end

  describe "#pre_tool_use" do
    %w[db/schema.rb db/structure.sql db/queue_schema.rb db/animals_structure.sql].each do |schema|
      it "blocks Write and Edit of #{schema}" do
        %w[Write Edit].each do |tool|
          decision = call(tool, File.join(root, schema))

          expect(decision.allowed?).to be(false)
          expect(decision.message).to eq("#{schema} is generated by Rails. Do not edit it by hand: change the schema " \
            "with a migration (bin/rails g migration ...) and run bin/rails db:migrate.")
        end
      end
    end

    it "blocks Write of a new migration, including secondary databases" do
      %w[db/migrate/20990101000000_x.rb db/cache_migrate/20261030000000_create_y.rb].each do |migration|
        decision = call("Write", File.join(root, migration))

        expect(decision.allowed?).to be(false)
        expect(decision.message).to start_with("Do not hand-write migration files. Create it with bin/rails g migration")
      end
    end

    it "allows Write and Edit of an existing migration" do
      touch(root, "db/migrate/20261030000000_create_posts.rb", "x")

      expect(call("Write", File.join(root, "db/migrate/20261030000000_create_posts.rb")).allowed?).to be(true)
      expect(call("Edit", File.join(root, "db/migrate/20261030000000_create_posts.rb")).allowed?).to be(true)
    end

    it "allows Edit of a migration path (Edit needs an existing file anyway) and other files" do
      expect(call("Edit", File.join(root, "db/migrate/20261030000000_x.rb")).allowed?).to be(true)
      expect(call("Write", File.join(root, "app/models/post.rb")).allowed?).to be(true)
      expect(call("Write", File.join(root, "db/seeds.rb")).allowed?).to be(true)
      expect(call("Write", File.join(root, "db/migrate/nested/x.rb")).allowed?).to be(true)
    end

    it "allows Bash and other tools" do
      decision = guard.pre_tool_use("tool_name" => "Bash", "tool_input" => {"command" => "bin/rails g migration AddX x:string"})

      expect(decision.allowed?).to be(true)
      expect(call("Read", File.join(root, "db/schema.rb")).allowed?).to be(true)
    end

    it "accepts root-relative, absolute and Windows-style paths, and ignores files outside the project" do
      expect(call("Edit", "db/schema.rb").allowed?).to be(false)
      expect(call("Edit", File.join(root, "db/schema.rb")).allowed?).to be(false)
      expect(call("Edit", File.join(root, "db\\schema.rb")).allowed?).to be(false)
      expect(call("Edit", "/elsewhere/db/schema.rb").allowed?).to be(true)
    end

    it "blocks a new migration when the project root is a symlink, whichever path spelling is used" do
      Dir.mktmpdir do |dir|
        link = File.join(dir, "link")
        File.symlink(root, link)
        FileUtils.mkdir_p(File.join(root, "db/migrate"))
        migration = "db/migrate/20990101000000_x.rb"

        expect(call("Write", File.join(link, migration), guard: described_class.new(root: link, config: load_config(root))).allowed?).to be(false)
        expect(call("Write", File.join(File.realpath(root), migration), guard: described_class.new(root: link, config: load_config(root))).allowed?).to be(false)
        expect(call("Write", File.join(link, migration), guard: described_class.new(root: File.realpath(root), config: load_config(root))).allowed?).to be(false)
        expect(call("Write", File.join(link, "db/new_dir/20990101000000_x.rb"), guard: described_class.new(root: link, config: load_config(root))).allowed?).to be(true)
      end
    end

    it "blocks paths in any case (case-insensitive filesystems)" do
      expect(call("Edit", File.join(root, "db/Schema.rb")).allowed?).to be(false)
      expect(call("Write", File.join(root, "DB/migrate/20990101000000_x.rb")).allowed?).to be(false)
    end

    it "allows malformed payloads" do
      expect(guard.pre_tool_use({}).allowed?).to be(true)
      expect(guard.pre_tool_use("tool_name" => "Write", "tool_input" => "x").allowed?).to be(true)
      expect(guard.pre_tool_use("tool_name" => "Write", "tool_input" => {"file_path" => ""}).allowed?).to be(true)
    end

    it "respects each guard's toggle independently" do
      no_schema = guard("guards:\n  schema:\n    enabled: false\n")
      expect(call("Edit", "db/schema.rb", guard: no_schema).allowed?).to be(true)
      expect(call("Write", "db/migrate/20990101000000_x.rb", guard: no_schema).allowed?).to be(false)

      no_migrations = guard("guards:\n  migrations:\n    enabled: false\n")
      expect(call("Write", "db/migrate/20990101000000_x.rb", guard: no_migrations).allowed?).to be(true)
      expect(call("Edit", "db/schema.rb", guard: no_migrations).allowed?).to be(false)
    end
  end

  it "classifies migration and schema paths" do
    expect(described_class.migration?("db/migrate/20261030000000_x.rb")).to be(true)
    expect(described_class.migration?("db/queue_migrate/20261030000000_x.rb")).to be(true)
    expect(described_class.migration?("db/migrate/x.txt")).to be(false)
    expect(described_class.schema?("db/schema.rb")).to be(true)
    expect(described_class.schema?("db/cable_schema.rb")).to be(true)
    expect(described_class.schema?("db/seeds.rb")).to be(false)
    expect(described_class.schema?("lib/db/schema.rb")).to be(false)
  end
end
