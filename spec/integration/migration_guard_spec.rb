# frozen_string_literal: true

require "json"

RSpec.describe "migration/schema guard" do
  # Installs the harness in a dummy copy and commits it, so only the example's own changes count.
  def with_installed_app
    with_dummy_app_copy do |app_root|
      output, status = run_in(app_root, "bin/rails g agent_harness:install")
      raise "install failed:\n#{output}" unless status.success?

      run_in(app_root, "git add -A && git -c user.email=test@example.com -c user.name=Test commit -q -m install")
      yield app_root
    end
  end

  it "passes for a generated migration after db:migrate" do
    with_installed_app do |app_root|
      output, status = run_in(app_root, "bin/rails g migration AddPublishedToPosts published:boolean && bin/rails db:migrate")
      expect(status).to be_success, output

      output, status = run_in(app_root, "bin/agent-check --only migrations")
      expect(status.exitstatus).to eq(0), output
      expect(output).to match(/\Aagent-check: PASS \(migrations\) - \d+ files checked/)
    end
  end

  it "fails for a hand-written migration" do
    with_installed_app do |app_root|
      File.write(File.join(app_root, "db/migrate/add_views_to_posts.rb"), <<~RUBY)
        class AddViewsToPosts < ActiveRecord::Migration[8.1]
          def change
            add_column :posts, :views, :integer
          end
        end
      RUBY

      output, status = run_in(app_root, "bin/agent-check --only migrations")
      expect(status.exitstatus).to eq(1), output
      expect(output).to include("db/migrate/add_views_to_posts.rb: does not look generated by bin/rails g migration")
    end
  end

  it "fails for a hand-edited db/schema.rb" do
    with_installed_app do |app_root|
      schema = File.join(app_root, "db/schema.rb")
      File.write(schema, File.read(schema).sub('t.string "title"', "t.string \"title\"\n    t.integer \"views\""))

      output, status = run_in(app_root, "bin/agent-check --only migrations")
      expect(status.exitstatus).to eq(1), output
      expect(output).to include("db/schema.rb changed without a migration: do not edit it by hand.")
    end
  end

  it "blocks a Write of a new migration file through the PreToolUse hook" do
    with_installed_app do |app_root|
      payload = JSON.generate("tool_name" => "Write", "tool_input" => {"file_path" => File.join(app_root, "db/migrate/20990101000000_x.rb")})

      stdout, stderr, status = Open3.capture3({"BUNDLE_GEMFILE" => DummyAppHelper::GEMFILE},
        "bin/agent-check", "hook", "pre-tool-use", stdin_data: payload, chdir: app_root)

      expect(status.exitstatus).to eq(2), stderr
      expect(stderr).to start_with("Do not hand-write migration files.")
      expect(stdout).to be_empty
      settings = JSON.parse(File.read(File.join(app_root, ".claude/settings.json")))
      expect(settings.dig("hooks", "PreToolUse", 0, "hooks", 0, "command")).to end_with("bin/agent-check hook pre-tool-use")
    end
  end
end
