# frozen_string_literal: true

require "rails_agent_harness/cli"

RSpec.describe RailsAgentHarness::ClientHook do
  around do |example|
    Dir.mktmpdir("client_hooks") do |root|
      @root = root
      example.run
    end
  end

  def invoke(client, phase, payload)
    @out = StringIO.new
    @err = StringIO.new
    @status = RailsAgentHarness::CLI.start(["client-hook", client, phase], root: @root,
      stdin: StringIO.new(JSON.generate(payload)), stdout: @out, stderr: @err)
    @out.string.empty? ? {} : JSON.parse(@out.string)
  end

  def edit_payload(client, path)
    case client
    when "codex"
      {"tool_name" => "apply_patch", "tool_input" => {"command" => "*** Begin Patch\n*** Add File: #{path}\n+x\n*** End Patch"}}
    when "copilot"
      {"toolName" => "create", "toolArgs" => JSON.generate("path" => path)}
    when "cursor"
      {"tool_name" => "Write", "tool_input" => {"path" => path}}
    when "gemini"
      {"tool_name" => "write_file", "tool_input" => {"file_path" => path}}
    end
  end

  %w[codex copilot cursor gemini].each do |client|
    it "blocks a new migration in #{client}'s protocol" do
      result = invoke(client, "pre", edit_payload(client, "db/migrate/20991231000000_bad.rb"))
      expect(@status).to eq(0)
      expect(result.to_s).to include("Do not hand-write migration")
      case client
      when "codex"
        expect(result.dig("hookSpecificOutput", "permissionDecision")).to eq("deny")
      when "copilot"
        expect(result["permissionDecision"]).to eq("deny")
      when "cursor"
        expect(result["permission"]).to eq("deny")
      when "gemini"
        expect(result["decision"]).to eq("deny")
      end
    end

    it "allows normal files and existing migrations in #{client}" do
      expect(invoke(client, "pre", edit_payload(client, "app/models/post.rb"))).to eq({})
      FileUtils.mkdir_p(File.join(@root, "db/migrate"))
      File.write(File.join(@root, "db/migrate/existing.rb"), "")
      expect(invoke(client, "pre", edit_payload(client, "db/migrate/existing.rb"))).to eq({})
    end

    it "blocks schema writes in #{client}" do
      expect(invoke(client, "pre", edit_payload(client, "db/schema.rb")).to_s).to include("generated by Rails")
    end

    it "feeds stop failures back once in #{client}" do
      allow(RailsAgentHarness::CLI).to receive(:start).and_call_original
      allow(RailsAgentHarness::CLI).to receive(:start).with([], any_args) do |*, **kwargs|
        kwargs[:stdout].puts "check failed"
        1
      end
      result = invoke(client, "stop", {"status" => "completed"})
      expect(result.to_s).to include("check failed")
      expected = {"cursor" => ["followup_message", "check failed\n"], "gemini" => ["decision", "deny"]}
      key, value = expected.fetch(client, ["decision", "block"])
      expect(result[key]).to eq(value)
      expect(invoke(client, "stop", {"status" => "completed", "stop_hook_active" => true, "loop_count" => 1})).to eq({})
    end
  end

  %w[codex copilot cursor gemini].each do |client|
    it "runs post-edit lint through the shared checker in #{client}" do
      allow(RailsAgentHarness::CLI).to receive(:start).and_call_original
      allow(RailsAgentHarness::CLI).to receive(:start).with(["--only", "rubocop", "--files", "app/models/post.rb"], any_args) do |*, **kwargs|
        kwargs[:stdout].puts "lint failed"
        1
      end
      payload = (client == "cursor") ? {"file_path" => "app/models/post.rb"} : edit_payload(client, "app/models/post.rb")
      result = invoke(client, "post", payload)
      expect(@status).to eq(0)
      if client == "cursor"
        expect(@err.string).to include("lint failed")
      else
        expect(result.to_s).to include("lint failed")
      end
    end
  end

  it "blocks creation through Copilot's edit tool, not only create" do
    payload = {"toolName" => "str_replace_editor", "toolArgs" => {"command" => "create", "path" => "db/migrate/new.rb"}}
    expect(invoke("copilot", "pre", payload)["permissionDecision"]).to eq("deny")
  end

  it "rejects recognized edits without a path" do
    invoke("gemini", "pre", {"tool_name" => "write_file", "tool_input" => {}})
    expect(@status).to eq(1)
  end

  it "allows read-only Copilot editor views of generated schema" do
    payload = {"toolName" => "str_replace_editor", "toolArgs" => {"command" => "view", "path" => "db/schema.rb"}}
    expect(invoke("copilot", "pre", payload)).to eq({})
  end

  it "handles non-ASCII hook bytes under an ASCII locale" do
    payload = edit_payload("gemini", "db/migrate/new.rb").merge("message" => "revisión")
    output = StringIO.new
    status = RailsAgentHarness::CLI.start(%w[client-hook gemini pre], root: @root,
      stdin: StringIO.new(JSON.generate(payload).force_encoding(Encoding::US_ASCII)), stdout: output, stderr: StringIO.new)
    expect(status).to eq(0)
    expect(JSON.parse(output.string)["decision"]).to eq("deny")
  end

  it "ignores arbitrary arguments from unrelated tools" do
    expect(invoke("copilot", "pre", {"toolName" => "unrelated", "toolArgs" => "freeform"})).to eq({})
    expect(@status).to eq(0)
  end

  it "guards Copilot patches, including freeform input" do
    patch = "*** Begin Patch\n*** Add File: db/schema.rb\n+x\n*** End Patch"
    [patch, {"input" => patch}, JSON.generate("patch" => patch)].each do |args|
      expect(invoke("copilot", "pre", {"toolName" => "apply_patch", "toolArgs" => args})["permissionDecision"]).to eq("deny")
    end
  end

  it "normalizes whitespace and CRLF in patch headers" do
    ["*** Add File: db/schema.rb ", "  *** Add File: db/schema.rb\r", "*** Update File: app/a.rb\r\n*** Move to: db/schema.rb\r"].each do |header|
      payload = {"tool_name" => "apply_patch", "tool_input" => {"command" => "*** Begin Patch\r\n#{header}\r\n+x\r\n*** End Patch"}}
      expect(invoke("codex", "pre", payload).dig("hookSpecificOutput", "permissionDecision")).to eq("deny")
    end
  end

  it "examines every path and rename destination in a Codex patch" do
    payload = {"tool_name" => "apply_patch", "tool_input" => {"command" => "*** Update File: app/a.rb\n*** Move to: db/schema.rb\n*** Add File: app/b.rb"}}
    expect(invoke("codex", "pre", payload).to_s).to include("generated by Rails")
  end

  it "does not interpret patch body text as a header" do
    payload = {"tool_name" => "apply_patch", "tool_input" => {"command" => "*** Update File: app/a.rb\n+*** Add File: db/schema.rb"}}
    expect(invoke("codex", "pre", payload)).to eq({})
  end

  it "rejects malformed edit arguments without printing their contents" do
    invoke("copilot", "pre", {"toolName" => "create", "toolArgs" => "invalid"})
    expect(@status).to eq(1)
  end
end
