# frozen_string_literal: true

require "rails_agent_harness/checks"

RSpec.describe RailsAgentHarness::Checks::Migrations do
  def schema_v1
    <<~RUBY
      ActiveRecord::Schema[8.1].define(version: 2026_10_01_000000) do
        create_table "posts" do |t|
          t.string "title"
        end
      end
    RUBY
  end

  def schema(version)
    schema_v1.sub("2026_10_01_000000", version.to_s.scan(/\A(\d{4})(\d{2})(\d{2})(\d{6})\z/).first.join("_"))
  end

  def migration(name = "AddPublishedToPosts")
    <<~RUBY
      class #{name} < ActiveRecord::Migration[8.1]
        def change
          add_column :posts, :published, :boolean
        end
      end
    RUBY
  end

  # A repo on `main` with a schema, then a `feature` branch; the block makes changes.
  def with_app(schema_file: "db/schema.rb", schema_content: schema_v1)
    with_git_repo(schema_file => schema_content, "db/migrate/20261001000000_create_posts.rb" => migration("CreatePosts")) do |root|
      git(root, "checkout", "-q", "-b", "feature")
      yield root
    end
  end

  def check(root, profile: build_profile, config: load_config(root))
    changes = RailsAgentHarness::ChangedFiles.new(root, base_branch: "main")
    described_class.new(root: root, config: config, profile: profile, files: changes.list, runner: nil, added: changes.added).call
  end

  it "passes for a generated-looking migration with an updated schema" do
    with_app do |root|
      touch(root, "db/migrate/20261030120000_add_published_to_posts.rb", migration)
      touch(root, "db/schema.rb", schema("20261030120000"))

      expect(check(root).status).to eq(:pass)
    end
  end

  it "accepts acronym class names case-insensitively" do
    with_app do |root|
      touch(root, "db/migrate/20261030120000_add_api_key_to_users.rb", migration("AddAPIKeyToUsers"))
      touch(root, "db/schema.rb", schema("20261030120000"))

      expect(check(root).status).to eq(:pass)
    end
  end

  it "flags a migration that doesn't look generated" do
    with_app do |root|
      touch(root, "db/migrate/add_views_to_posts.rb", migration("AddViewsToPosts"))
      touch(root, "db/schema.rb", schema("20261030120000"))

      result = check(root)
      expect(result).to have_attributes(status: :fail, summary: "1 problem")
      expect(result.details).to eq(["db/migrate/add_views_to_posts.rb: does not look generated by bin/rails g migration (expected YYYYMMDDHHMMSS_snake_name.rb)"])
    end
  end

  it "flags an invalid or future timestamp" do
    with_app do |root|
      touch(root, "db/migrate/20261340120000_add_x.rb", migration("AddX"))
      touch(root, "db/migrate/20990101000000_add_y.rb", migration("AddY"))
      touch(root, "db/schema.rb", schema("20990101000000"))

      expect(check(root).details).to eq([
        "db/migrate/20261340120000_add_x.rb: does not look generated by bin/rails g migration (expected YYYYMMDDHHMMSS_snake_name.rb)",
        "db/migrate/20990101000000_add_y.rb: does not look generated by bin/rails g migration (expected YYYYMMDDHHMMSS_snake_name.rb)"
      ])
    end
  end

  it "flags a wrong class name" do
    with_app do |root|
      touch(root, "db/migrate/20261030120000_add_published_to_posts.rb", migration("AddPublished"))
      touch(root, "db/schema.rb", schema("20261030120000"))

      expect(check(root).details).to eq([
        "db/migrate/20261030120000_add_published_to_posts.rb: expected `class AddPublishedToPosts < ActiveRecord::Migration[x.y]` (as bin/rails g migration generates it)"
      ])
    end
  end

  it "flags a migration without a schema change" do
    with_app do |root|
      touch(root, "db/migrate/20261030120000_add_published_to_posts.rb", migration)

      expect(check(root).details).to eq(["migration added but db/schema.rb not updated: run bin/rails db:migrate"])
    end
  end

  it "flags a schema version older than the newest migration" do
    with_app do |root|
      touch(root, "db/migrate/20261030120000_add_published_to_posts.rb", migration)
      touch(root, "db/schema.rb", schema("20261015000000"))

      expect(check(root).details.first).to start_with("migration added but db/schema.rb not updated (its version is older than 20261030120000)")
    end
  end

  it "flags a schema change without a migration" do
    with_app do |root|
      touch(root, "db/schema.rb", schema_v1.sub('t.string "title"', 't.string "title"' + "\n    t.integer \"views\""))

      expect(check(root).details).to eq([
        "db/schema.rb changed without a migration: do not edit it by hand. Revert it (git checkout -- db/schema.rb) and use a migration."
      ])
    end
  end

  it "allows a schema change that comes with an edited migration" do
    with_app do |root|
      touch(root, "db/migrate/20261001000000_create_posts.rb", migration("CreatePosts") + "\n")
      touch(root, "db/schema.rb", schema_v1 + "\n")

      expect(check(root).status).to eq(:pass)
    end
  end

  it "checks db/structure.sql for SQL-format apps" do
    with_app(schema_file: "db/structure.sql", schema_content: "CREATE TABLE posts ();\n") do |root|
      touch(root, "db/migrate/20261030120000_add_published_to_posts.rb", migration)
      sql = build_profile(schema_format: :sql)

      expect(check(root, profile: sql).details).to eq(["migration added but db/structure.sql not updated: run bin/rails db:migrate"])

      touch(root, "db/structure.sql", "CREATE TABLE posts ();\nINSERT INTO schema_migrations VALUES ('20261030120000');\n")
      expect(check(root, profile: sql).status).to eq(:pass)
    end
  end

  it "applies only rules 1-2 to secondary databases" do
    with_app do |root|
      touch(root, "db/queue_migrate/20261030120000_create_jobs.rb", migration("CreateJobs"))

      expect(check(root).status).to eq(:pass)

      touch(root, "db/queue_migrate/create_more_jobs.rb", migration("CreateMoreJobs"))
      expect(check(root).details.size).to eq(1)
    end
  end

  it "toggles the migration and schema rules independently" do
    with_app do |root|
      touch(root, "db/migrate/add_views.rb", migration("AddViews"))

      no_migrations = check(root, config: load_config(root, "guards:\n  migrations:\n    enabled: false\n"))
      expect(no_migrations.details).to eq(["migration added but db/schema.rb not updated: run bin/rails db:migrate"])

      no_schema = check(root, config: load_config(root, "guards:\n  schema:\n    enabled: false\n"))
      expect(no_schema.details).to eq(["db/migrate/add_views.rb: does not look generated by bin/rails g migration (expected YYYYMMDDHHMMSS_snake_name.rb)"])
    end
  end

  it "skips when both guards are disabled or nothing relevant changed" do
    with_app do |root|
      touch(root, "app/models/post.rb", "x")
      expect(check(root)).to have_attributes(status: :skip, summary: "no migration or schema changes")

      touch(root, "db/schema.rb", "edited")
      disabled = load_config(root, "guards:\n  migrations:\n    enabled: false\n  schema:\n    enabled: false\n")
      expect(check(root, config: disabled)).to have_attributes(status: :skip, summary: "guards disabled in config/agent_harness.yml")
    end
  end

  it "reports invalid UTF-8 in a migration as a finding, not a crash" do
    with_app do |root|
      File.binwrite(File.join(root, "db/migrate/20261030120000_add_published_to_posts.rb"), "# \xFF\xFE\n" + migration)
      File.binwrite(File.join(root, "db/schema.rb"), "# \xFF\n" + schema("20261030120000"))

      expect(check(root).status).to eq(:pass)
    end
  end

  it "works out added files with git when they aren't passed in" do
    with_app do |root|
      touch(root, "db/migrate/add_views.rb", migration("AddViews"))
      touch(root, "db/schema.rb", schema("20261030120000"))
      result = described_class.new(root: root, config: load_config(root), profile: build_profile,
        files: %w[db/migrate/add_views.rb db/schema.rb], runner: nil).call

      expect(result.details.first).to start_with("db/migrate/add_views.rb: does not look generated")
    end
  end
end
