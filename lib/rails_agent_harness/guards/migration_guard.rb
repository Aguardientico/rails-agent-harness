# frozen_string_literal: true

require "time"
require "rails_agent_harness/paths"

module RailsAgentHarness
  module Guards
    # Stops agents from hand-writing migrations and hand-editing the schema. Two layers:
    #
    # 1. #pre_tool_use, for Claude Code's PreToolUse hook (precise: it sees the tool call
    #    before it happens):
    #    - schema guard: blocks Write/Edit of a schema file (db/schema.rb, db/structure.sql,
    #      db/*_schema.rb, db/*_structure.sql);
    #    - migrations guard: blocks Write of a migration file (db/migrate/*.rb,
    #      db/*_migrate/*.rb) that doesn't exist yet. Editing a generated migration, and any
    #      Bash call such as `bin/rails g migration`, is allowed.
    #
    # 2. Checks::Migrations, a heuristic in bin/agent-check for every agent:
    #    1. (migrations) each added migration is named YYYYMMDDHHMMSS_snake_name.rb with a valid
    #       UTC timestamp at most 24h in the future;
    #    2. (migrations) it defines `class <SnakeName camelized> < ActiveRecord::Migration[x.y]`
    #       (compared case-insensitively, so acronyms like AddAPIKey pass);
    #    3. (schema) when a migration is added, the app's schema file changed too, and
    #       db/schema.rb's `define(version: ...)` is >= the newest added migration;
    #    4. (schema) a schema file changed without any migration being added or modified.
    #
    # Known limits (see docs/migration_guard.md):
    # - Without the hook, an agent can still hand-write a perfectly generator-shaped file.
    # - A legitimate `db:migrate` after pulling base-branch migrations changes the schema
    #   without a migration on this branch and trips rule 4: commit that separately, or set
    #   `guards.schema.enabled: false`. The same goes for the first `db:migrate` after
    #   upgrading to Rails 8.1, which re-dumps db/schema.rb with columns sorted alphabetically.
    # - Rule 3 only checks the primary database (db/migrate); secondary databases
    #   (db/<name>_migrate) get rules 1-2.
    # - Non-timestamped migrations (`timestamped_migrations = false`) fail rule 1.
    class MigrationGuard
      Decision = Data.define(:allowed, :message) do
        def allowed? = allowed
      end

      # Case-insensitive, so `db/Schema.rb` can't slip past the hook on a case-insensitive
      # filesystem (macOS' default).
      MIGRATION = %r{\Adb/(migrate|[^/]+_migrate)/[^/]+\.rb\z}i
      SCHEMA = %r{\Adb/((schema|[^/]+_schema)\.rb|(structure|[^/]+_structure)\.sql)\z}i
      PRIMARY_MIGRATION = %r{\Adb/migrate/}i
      FILENAME = /\A(\d{14})_([a-z0-9_]+)\.rb\z/
      FILE_TOOLS = %w[Write Edit].freeze

      def self.migration?(path) = MIGRATION.match?(path)

      def self.schema?(path) = SCHEMA.match?(path)

      def initialize(root:, config:)
        @root = root.to_s
        @config = config
      end

      # `payload` is the parsed PreToolUse hook input (`tool_name`, `tool_input.file_path`,
      # absolute or root-relative). Anything that isn't a Write/Edit of a file in the project
      # is allowed.
      def pre_tool_use(payload)
        tool_name = payload["tool_name"]
        tool_input = payload["tool_input"]
        file_path = tool_input["file_path"] if tool_input.is_a?(Hash)
        return allow unless FILE_TOOLS.include?(tool_name) && file_path.is_a?(String) && !file_path.empty?

        file = Paths.relative(file_path, @root)
        return allow unless file

        if @config.guard_enabled?(:schema) && self.class.schema?(file)
          return block("#{file} is generated by Rails. Do not edit it by hand: change the schema " \
            "with a migration (bin/rails g migration ...) and run bin/rails db:migrate.")
        end
        if @config.guard_enabled?(:migrations) && tool_name == "Write" && self.class.migration?(file) &&
            !File.exist?(File.join(@root, file))
          return block("Do not hand-write migration files. Create it with bin/rails g migration " \
            "AddFooToBars foo:string (or bin/rails g model ...), then edit the generated file and " \
            "run bin/rails db:migrate.")
        end

        allow
      end

      # Problems (one line each) for the changed files. `added` are the files added since the
      # merge base; `schema_format` is :ruby or :sql.
      def problems(files:, added:, schema_format:)
        added_migrations = added.select { |file| self.class.migration?(file) }
        problems = []
        problems.concat(added_migrations.flat_map { |file| migration_problems(file) }) if @config.guard_enabled?(:migrations)
        problems.concat(schema_problems(files, added_migrations, schema_format)) if @config.guard_enabled?(:schema)
        problems
      end

      def self.timestamp(file)
        File.basename(file)[FILENAME, 1]
      end

      private

      def allow = Decision.new(allowed: true, message: nil)

      def block(message) = Decision.new(allowed: false, message: message)

      # Rules 1 and 2.
      def migration_problems(file)
        match = FILENAME.match(File.basename(file))
        unless match && valid_timestamp?(match[1])
          return ["#{file}: does not look generated by bin/rails g migration (expected YYYYMMDDHHMMSS_snake_name.rb)"]
        end

        expected = match[2].split("_").map(&:capitalize).join
        source = File.read(File.join(@root, file), encoding: "UTF-8").scrub
        name = source[/^\s*class\s+([A-Za-z0-9_:]+)\s*<\s*ActiveRecord::Migration\[\d+\.\d+\]/, 1]
        return [] if name && name.split("::").last.casecmp?(expected)

        ["#{file}: expected `class #{expected} < ActiveRecord::Migration[x.y]` (as bin/rails g migration generates it)"]
      end

      def valid_timestamp?(digits)
        time = Time.strptime("#{digits} UTC", "%Y%m%d%H%M%S %Z")
        time.strftime("%Y%m%d%H%M%S") == digits && time <= Time.now.utc + 24 * 60 * 60
      rescue ArgumentError
        false
      end

      # Rules 3 and 4.
      def schema_problems(files, added_migrations, schema_format)
        schema_file = (schema_format == :sql) ? "db/structure.sql" : "db/schema.rb"
        primary = added_migrations.grep(PRIMARY_MIGRATION)
        newest = primary.filter_map { |file| self.class.timestamp(file) }.max
        problems = []
        if primary.any?
          if !files.include?(schema_file)
            problems << "migration added but #{schema_file} not updated: run bin/rails db:migrate"
          elsif schema_format == :ruby && newest && schema_version.to_s < newest
            problems << "migration added but #{schema_file} not updated (its version is older than " \
              "#{newest}): run bin/rails db:migrate"
          end
        end

        changed_schemas = files.select { |file| self.class.schema?(file) }
        if changed_schemas.any? && files.none? { |file| self.class.migration?(file) }
          changed_schemas.each do |schema|
            problems << "#{schema} changed without a migration: do not edit it by hand. Revert it " \
              "(git checkout -- #{schema}) and use a migration."
          end
        end
        problems
      end

      # db/schema.rb's `define(version: 2026_10_30_000000)` without underscores, or nil.
      def schema_version
        path = File.join(@root, "db/schema.rb")
        return unless File.file?(path)

        File.read(path, encoding: "UTF-8").scrub[/define\(version:\s*([\d_]+)\)/, 1]&.delete("_")
      end
    end
  end
end
